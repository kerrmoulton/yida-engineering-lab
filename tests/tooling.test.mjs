test('live guard allows only a blank page without a baseline', () => {
  assert.deepEqual(
    assessLiveBaseline({
      baseline: null,
      appType: 'APP_TEST',
      formUuid: 'FORM_TEST',
      liveSemanticSha256: 'blank',
      runtimeCode: '',
    }),
    { mode: 'initial-blank-page' },
  );
  assert.throws(
    () =>
      assessLiveBaseline({
        baseline: null,
        appType: 'APP_TEST',
        formUuid: 'FORM_TEST',
        liveSemanticSha256: 'occupied',
        runtimeCode: 'existing code',
      }),
    /停止首次发布/,
  );
});

test('live guard blocks drift and accepts an exact baseline', () => {
  const baseline = {
    appType: 'APP_TEST',
    formUuid: 'FORM_TEST',
    liveSemanticSha256: 'expected',
  };
  assert.deepEqual(
    assessLiveBaseline({
      baseline,
      appType: 'APP_TEST',
      formUuid: 'FORM_TEST',
      liveSemanticSha256: 'expected',
      runtimeCode: 'code',
    }),
    { mode: 'baseline-match' },
  );
  assert.throws(
    () =>
      assessLiveBaseline({
        baseline,
        appType: 'APP_TEST',
        formUuid: 'FORM_TEST',
        liveSemanticSha256: 'changed',
        runtimeCode: 'code',
      }),
    /线上页面已偏离/,
  );
});
