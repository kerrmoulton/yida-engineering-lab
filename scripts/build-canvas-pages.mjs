import fs from 'node:fs/promises';
import path from 'node:path';
import { build } from 'esbuild';
import { createPageRouteMap, createServiceUrlMap, loadManifest, readJson, root, run } from './lib.mjs';
import { createCanvasPublishSource, createCanvasRuntimeSource } from './tailwind-build-lib.mjs';

const requireTargets = process.argv.includes('--require-targets');
const manifest = await loadManifest();
const routes = createPageRouteMap(manifest, { requireRemote: requireTargets });
const services = createServiceUrlMap(manifest, { requireConfigured: requireTargets });
const tailwindPages = manifest.pages.filter((page) => page.build?.kind === 'tailwind');
let css = null;

if (tailwindPages.length) {
  const buildDefinitions = new Set(
    tailwindPages.map((page) => JSON.stringify([page.build.styleEntry, page.build.config])),
  );
  if (buildDefinitions.size !== 1) {
    throw new Error('当前构建器要求所有 Tailwind 页面共享 styleEntry 和 config');
  }
  const [tailwindPage] = tailwindPages;
  const cacheDirectory = path.join(root, '.cache/experiments/tailwind');
  const generatedCssPath = path.join(cacheDirectory, 'tailwind.css');
  await fs.mkdir(cacheDirectory, { recursive: true });
  run(
    path.join(root, 'node_modules/.bin/tailwindcss'),
    [
      '-i',
      tailwindPage.build.styleEntry,
      '-o',
      path.relative(root, generatedCssPath),
      '--config',
      tailwindPage.build.config,
      '--minify',
    ],
    { echo: true },
  );
  css = await fs.readFile(generatedCssPath, 'utf8');
}

const outputs = [];
for (const page of manifest.pages) {
  const authorSourcePath = path.join(root, page.authorSource);
  const outputPath = path.join(root, page.source);
  let output;
  if (page.build?.kind === 'tailwind') {
    const authorSource = await fs.readFile(authorSourcePath, 'utf8');
    output = createCanvasPublishSource(authorSource, css, routes);
  } else if (page.build?.kind === 'canvas') {
    const authorSource = await fs.readFile(authorSourcePath, 'utf8');
    output = createCanvasRuntimeSource(authorSource, routes);
  } else if (page.build?.kind === 'esbuild-canvas') {
    const contract = await readJson(page.contract);
    const runtimeModule = `
const PAGE_ROUTES = ${JSON.stringify(routes)};
const SERVICE_URLS = ${JSON.stringify(services)};
export function getLabPageUrl(key) {
  const value = PAGE_ROUTES[key];
  if (!value) throw new Error('Unknown Yida Lab page key: ' + key);
  return value;
}
export function getLabServiceUrl(key) {
  const value = SERVICE_URLS[key];
  if (!value) throw new Error('Unknown Yida Lab service key: ' + key);
  return value;
}`;
    const result = await build({
      entryPoints: [authorSourcePath],
      bundle: true,
      write: false,
      format: 'esm',
      platform: 'browser',
      target: 'es2020',
      jsx: 'transform',
      minifySyntax: true,
      external: contract.allowedImports,
      plugins: [
        {
          name: 'yida-lab-runtime',
          setup(buildContext) {
            buildContext.onResolve({ filter: /^@yida-lab\/runtime$/ }, () => ({
              path: '@yida-lab/runtime',
              namespace: 'yida-lab',
            }));
            buildContext.onLoad({ filter: /.*/, namespace: 'yida-lab' }, () => ({
              contents: runtimeModule,
              loader: 'js',
            }));
          },
        },
      ],
      logLevel: 'warning',
    });
    if (result.outputFiles.length !== 1) {
      throw new Error(`页面 ${page.key} 的 esbuild 产物数量不是 1`);
    }
    const bundledSource = result.outputFiles[0].text;
    output = bundledSource.replace(
      /export\s*\{\s*(\w+)\s+as\s+default\s*\};?\s*$/,
      (_match, defaultExportName) =>
        defaultExportName === 'YidaComp' || /(?:function|const|let|class)\s+YidaComp\b/.test(bundledSource)
          ? 'export default YidaComp;\n'
          : `const YidaComp=${defaultExportName};export default YidaComp;\n`,
    );
    output = `// Generated by npm run build:canvas. Do not edit.\n${output}`;
  } else {
    throw new Error(`页面 ${page.key} 使用了未知构建类型：${page.build?.kind}`);
  }
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, output, 'utf8');
  outputs.push({
    pageKey: page.key,
    authorSource: page.authorSource,
    output: page.source,
    outputBytes: Buffer.byteLength(output),
  });
}

console.log(
  JSON.stringify(
    {
      success: true,
      routes,
      services,
      cssBytes: css ? Buffer.byteLength(css) : 0,
      outputs,
    },
    null,
    2,
  ),
);
