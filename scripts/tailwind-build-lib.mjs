const STYLE_IMPORT = /^import\s+['"]\.\/styles\.css['"];?\s*$/gm;
const LAB_RUNTIME_IMPORT = /^import\s+\{\s*getLabPageUrl\s*\}\s+from\s+['"]@yida-lab\/runtime['"];?\s*$/gm;

export function injectLabRuntime(authorSource, routes) {
  const runtimeImports = authorSource.match(LAB_RUNTIME_IMPORT) || [];
  if (runtimeImports.length !== 1) {
    throw new Error("作者源码必须且只能导入一次 getLabPageUrl from '@yida-lab/runtime'");
  }
  const runtimeModule = `const YIDA_LAB_PAGE_ROUTES = ${JSON.stringify(routes, null, 2)};
function getLabPageUrl(pageKey) {
  const url = YIDA_LAB_PAGE_ROUTES[pageKey];
  if (!url) throw new Error('Unknown Yida Lab page key: ' + pageKey);
  return url;
}`;
  return authorSource.replace(LAB_RUNTIME_IMPORT, runtimeModule);
}

export function createCanvasRuntimeSource(authorSource, routes) {
  if (authorSource.includes('YIDA_LAB_PAGE_ROUTES')) {
    throw new Error('作者源码不得包含生成态页面路由表');
  }
  return `// Generated by npm run build:canvas. Do not edit.\n${injectLabRuntime(authorSource, routes)}`;
}

export function createCanvasPublishSource(authorSource, css, routes) {
  if (authorSource.includes('GENERATED_TAILWIND_CSS')) {
    throw new Error('作者源码不得包含生成态 Tailwind CSS');
  }
  const styleImports = authorSource.match(STYLE_IMPORT) || [];
  if (styleImports.length !== 1) {
    throw new Error("作者源码必须且只能包含一次 import './styles.css'");
  }

  const styleModule = `const GENERATED_TAILWIND_CSS = ${JSON.stringify(css)};
const GENERATED_TAILWIND_STYLE_ID = 'yida-engineering-lab-tailwind';
if (typeof document !== 'undefined') {
  let generatedStyleElement = document.getElementById(GENERATED_TAILWIND_STYLE_ID);
  if (!generatedStyleElement) {
    generatedStyleElement = document.createElement('style');
    generatedStyleElement.id = GENERATED_TAILWIND_STYLE_ID;
    document.head.appendChild(generatedStyleElement);
  }
  generatedStyleElement.textContent = GENERATED_TAILWIND_CSS;
}`;

  const withRuntime = injectLabRuntime(authorSource, routes);
  return `// Generated by npm run build:canvas. Do not edit.\n${withRuntime.replace(STYLE_IMPORT, styleModule)}`;
}
